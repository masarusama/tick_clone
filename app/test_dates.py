meta = {"created": "2026-10-06T10:00:00+09:00"}
nd = store.note_dates(meta, "!10/8 提出\n普通の10/9の話\n```\n!10/10\n```\nwow !!\n![](attachments/x.png)")
want = [("2026-10-08", "due", "", "", ""), ("2026-10-08", "text", "", "", ""), ("2026-10-09", "text", "", "", "")]
