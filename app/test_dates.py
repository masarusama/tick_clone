from datetime import date
from dates import extract_dates

A = date(2026, 10, 6)  # 火曜日
cases = [
    ("明日までに返事", [date(2026, 10, 7)]),
    ("10/8 打合せ", [date(2026, 10, 8)]),
    ("10月8日に会う", [date(2026, 10, 8)]),
    ("2026/11/3 締切", [date(2026, 11, 3)]),
    ("2025年12月24日", [date(2025, 12, 24)]),
    ("来週火曜に約束", [date(2026, 10, 13)]),
    ("今週金曜まで", [date(2026, 10, 9)]),
    ("金曜日に行く", [date(2026, 10, 9)]),
    ("火曜日に行く", [date(2026, 10, 6)]),
    ("1/5 に更新", [date(2027, 1, 5)]),           # 年なし→基準日に最も近い年
    ("12/30 16万振込", [date(2026, 12, 30)]),     # 年なしは基準日に近い方（85日先 < 280日前）
    ("3/1 に済ませた", [date(2027, 3, 1)]),       # 来年3月(146日先)の方が今年3月(219日前)より近い
    ("https://example.com/2026/10/20/post", []),   # URLの中は無視
    ("090-0000-0000 990+1650", []),                 # 電話番号・金額は無視
    ("```\n10/8\n```", []),                         # コードブロックは無視
    ("#10/8 のタグ", []),                           # タグは無視
    ("2/30", []),                                   # 存在しない日
    ("明後日と来週月曜", [date(2026, 10, 8), date(2026, 10, 12)]),
]
bad = 0
for text, want in cases:
    got = extract_dates(text, A)
    ok = got == sorted(want)
    bad += not ok
    print("OK " if ok else "NG ", repr(text), got if not ok else "")

